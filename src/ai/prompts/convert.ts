import type { QuestionType } from "../../types";
import { QuestionType as QT } from "../../types";
import { materialExamplesFor, materialRulesFor, protocolSpec, typeRulesFor } from "./protocol";

/**
 * 转换域 prompt（20260910 自 ConvertService/ConvertDetect/KnowOutline 迁入
 * prompt 集中地）：整卷/增量共用的出题 prompt、前置检测窗口 prompt、
 * 知识大纲归纳 prompt。
 *
 * 出题 prompt 题型化（20260910）：前置检测顺带判断文档含哪些题型
 * （TYPES 行，零额外 AI 调用），buildPrompt 只拼在场题型的规则——
 * 数学卷不再带英语四类约定。types=undefined（检测失败/续跑无先验）
 * 走全量兜底，prompt 与题型化之前逐字节一致。
 */

/** 多步引导题的行协议示例（bigToSteps 开启时随 prompt 附带）。 */
const STEPS_EXAMPLE = `@@Q type=steps steps=method|result knowledge=考点 chapter=章节
@@P stem
计算大题题干……求 $\\lim_{x \\to 0}\\frac{\\sin x}{x}$
@@P step
第 1 步 · 选择方法：求解本题可行的方法是（ ）
@@P step-opt
洛必达法则
@@P step-opt
等价无穷小代换
@@P step-ans
AB
@@P step
第 2 步 · 等价无穷小代换：本步化简得（ ）
@@P step-opt
$1$
@@P step-opt
$0$
@@P step-opt
$\\infty$
@@P step-opt
$x$
@@P step-ans
A
@@P sol
完整解析（含每一步的推导）
@@END`;

/** 开关联动的补充题型：填空转选择产出 single、大题拆多步产出 steps——
 *  开关开着时对应题型约定必须在场（用户显式设置不受检测影响）。 */
function specTypesOf(
    types: QuestionType[] | undefined,
    fillToChoice: boolean,
    bigToSteps: boolean
): QuestionType[] | undefined {
    if (!types) return undefined;
    const extra: QuestionType[] = [...(fillToChoice ? [QT.Single] : []), ...(bigToSteps ? [QT.Steps] : [])];
    return [...new Set([...types, ...extra])];
}

/** 逐段自推进的批次上下文（20260910 起整卷转换不再预切块，批边界改由
 *  AI 按题目边界决定）：step 缺省=旧的「一次一块」批语义，增量重转换沿用。 */
export interface StepContext {
    /** 本批序号（从 1 起）。 */
    batch: number;
    /** 是否首批——首批额外输出 CAN_CONVERT/REASON/TYPES/**SUBJECT** 四行
     *  判定（判定步骤已合并进首批生成，不再单独跑一轮检测；行数与
     *  {@link verdictOf} 实发一致，正文口径不再是旧文案的「三行」）。 */
    first: boolean;
}

/** 逐段批的阅读约定 + `@@TO` 定位行协议（代码按该片段定位推进游标；
 *  末尾未完题留给下一批，故不会把一道题拦腰切断）。 */
function stepRulesOf(step: StepContext): string {
    return `\n\n本批的阅读方式（**必须遵守**）：你正在分段处理一份很长的文档，这是第 ${step.batch} 批，下面给你的**只是全文的一个片段**，不是全文：
- 片段开头可能承接上一批的未完内容，直接接着处理即可；
- 片段末尾可能有一道**没写完**的题（题干没结束、选项不全、解答没写完）——**不要**转这道题，把它整道留给下一批；
- 一道题的题干与其答案/解析**必须在同一批里处理完**，不许把题干与解答拆到两批。
本批处理完后，最后必须另起一行输出定位行（这一行不属于任何题目）：
@@TO: <原文逐字片段>
它表示「本批已处理到该片段所在的那一行为止」。片段取**本批处理完的最后一道题的最后一行**里的连续 10~20 个字，必须与原文**完全一致**（不得改写、省略、补全公式、翻译），不要加引号或任何说明。若本片段里的内容已全部处理完（末尾那道题也是完整的），输出 @@TO: END`;
}

/** 判定行措辞（逐段首批报四行、后续批次免报；旧模式两行与改造前一致）。 */
function verdictOf(step?: StepContext): string {
    const verdict = `CAN_CONVERT: yes 或 no
REASON: 一句话说明（不能转换时说明原因，能转换时概括题目覆盖范围）`;
    if (!step) return verdict;
    if (!step.first) return "（本批不需要输出 CAN_CONVERT / REASON / TYPES / SUBJECT 判定行，直接输出题目）";
    return `${verdict}
TYPES: 本片段的题型，逗号分隔（从 single/multiple/judge/fill/brief/steps/cloze/match/essay/trans 里挑，写中文也可以，如 单选/多选/判断/填空/简答/多步/完形/新题型/作文/翻译）；本片段没有现成题目时留空
SUBJECT: 本片段所属**学科**，只写一个词（如 英语/数学/语文/物理/化学/历史/政治/地理/生物，或专业课名如 自控原理/信号与系统）；**学科与题型是两件事**——语文卷的作文题（essay）与翻译题（trans）也是语文，英语阅读训练卷的单选题（single）也是英语，必须按内容判断；实在判断不出写「无」`;
}

/** 出题 prompt（20260902 起输出走行协议，kramdown 由代码渲染——格式
 *  规则只剩内容语义，超级块/IAL 语法全部消失）。knowRule/knowList 是
 *  知识点反链的追加插槽（KnowledgeLink 路由出小节时才有值）；
 *  types=题型先验（首批检测顺带报出/题集既有记录并集；undefined=全量兜底）；
 *  step=逐段自推进的批次上下文（undefined 走旧的一次一块批语义，增量
 *  重转换沿用，此时 prompt 与改造前逐字节一致）。
 *  bank=目标**是题库/原文档**（Issue #131）：整卷转换与增量重转换都传
 *  true，@@P opt 行改**逐题条件规则**（原文有现成题目→沿用原序与字母；
 *  新造题→正确项写最前）并启用解析的 `〔opt:X〕` 标记协议；出题链
 *  （加练/变式）不传，prompt 与改造前逐字节一致。 */
export function buildPrompt(
    source: string,
    fillToChoice = false,
    bigToSteps = false,
    knowRuleBlock = "",
    knowList = "",
    types?: QuestionType[],
    step?: StepContext,
    bank = false
): string {
    const specTypes = specTypesOf(types, fillToChoice, bigToSteps);
    // 填空转选择：一次对话内完成（不需要额外一轮 AI 调用）
    const fillRule = fillToChoice
        ? `
8. 填空转选择：原文中的填空题一律改写为 type="single" 的单选题——题干中的空格（____/（ ））改为（ ），正确答案即原空格答案，再编写 3 个与正确答案同类、似是而非但有明确错误的干扰项作为其余选项；解析里说明原填空答案。`
        : "";
    // 大题拆多步：可分解的工科大题 → 多步引导题（method/result 步）
    const stepsRule = bigToSteps
        ? `
9. 大题拆多步：原文中可分解的工科大题（计算/求值/化简，每步有确定的中间结果）改写为 type="steps" 的多步引导题——选定一条典型参考路径拆 2~5 步；方法分歧处设 method 步（选项为候选方法，@@P step-ans 写**全部可行方法**的字母集合如 AB，任选可行即对）；其余为 result 步考该步的中间结果，@@P step-ans 写唯一正确字母，干扰项来自常见计算错误；每步 3~4 个选项，结果步的引导语写明所用方法（如「第 2 步 · 等价无穷小代换：本步化简得（ ）」）；@@Q 行的 steps 按序声明每步类型（如 steps=method|result）；论述/证明/开放等不可分解的题仍用 type="brief"。示例：
${STEPS_EXAMPLE}`
        : "";
    const englishRules = materialRulesFor(specTypes);
    const head = step
        ? `你是思源笔记的出题助手。你把一份长文档**分段**转换成刷题题目——下面给你的只是全文的一个片段，不是全文。
${step.first ? "第一批先判断这段内容是否适合出题（有可考查的知识点、内容足够具体）并报出题型与学科，先输出四行判定（CAN_CONVERT / REASON / TYPES / SUBJECT）：" : "直接输出题目。"}`
        : `你是思源笔记的出题助手。把下面的文档内容转换成刷题题目。

判断该文档内容是否适合出题（有可考查的知识点、内容足够具体），先输出两行判定：`;
    const lead = step && !step.first ? "每道题" : "可出题时，随后每道题";
    return `${head}
${verdictOf(step)}

${lead}按以下${protocolSpec(specTypes, { bank })}
硬性规则：
${typeRulesFor(specTypes)}
2. 公式行内一律 $...$，块级一律 $$...$$ 各占一行；\\(...\\) 与 \\[ \\] 记法均改写、禁止出现。
3. 保留原文的公式与代码。
4. **题量与原文严格对应**：若原文是试卷/习题册/题解（有现成题目，或「题目+答案」结构），必须**一题对一题**——原文一道题输出一道题，原文的答案与解答写进该题的解析（@@P sol），不得漏题、不得合并、不得把一道题拆成多道、也不得自行新造；答案/解答只是该题的解析来源，**不得再为它单独出题**。只有原文是讲义/笔记（无现成题目）时才按知识点出题：内容少时至少 1 道，丰富时 5~12 道。

4.1 **真题优先（去重硬口径）**：同一份文档里，只要**存在**现成真题，就以真题为准——**不得**再为同一语篇/同一考点自造题（自造题与真题撞车的典型：自造的态度题 vs 真题的态度题、自造的细节题 vs 真题的细节题）。自造题**只用于完全没有现成题目的语篇/章节**（纯讲义、纯笔记、无题文章）。若本片段既有文章的讲解/翻译又有现成题目，照第 4 条一题对一题转真题，讲解只作解析来源。

4.2 **语篇（文章正文）一律出材料块，不得自造题**：考研英语/四六级/真题风格的**文章语篇**——成段英文文章正文，来源行/标题含「Text 1」「Text 2」「Part A」「Part B」「逐题细解」「逐句精讲」「真题」「Reading Comprehension」等特征即认定——**即使本片段没看到配套题目，也必须按材料输出**（@@Q material=1 + @@P body，有参考译文再加 @@P trans），**绝不允许为它自造题、也绝不允许跳过它**：这类语篇的配套真题几乎总在紧随其后的批次里。本片段里同时出现该语篇的配套真题（带现成题号）时，按第 7 条一题对一题、小题写 group=prev 挂靠该材料块。判定顺序：**先按特征认出语篇（本批即可出材料块），再看本批有没有配套真题**——两件事互不排斥。
5. **插图必须随题走**：原文档里的插图以占位行「〔插图:assets/文件名〕」出现，是该题依赖的插图（电路图/方框图/几何图等）时，把该插图**还原成标准 markdown 图片行**写进对应部件——半角 ! + 空方括号 + 小括号内为冒号后的完整原路径（示意形如 ![](插图原路径)），单独成段、路径与文件名一个字符都不能改；**不要**把〔插图:…〕占位原样写进输出。题目本身依赖的图（原理示意图/结构图，题干常写「如图/下图/图所示」）放题干（@@P stem）；答案/解析里给出的图（如解答画出的方框图）放解析（@@P sol）。没有插图的题**不要**编造图片行。
6. **禁止跳过带图题**：题干含「如图/下图/图所示」或题目相关段落配有插图占位行（〔插图:…〕）的题，必须与所有题一样逐题转换（插图按第 5 条还原）；因为题里有图、读不了图就跳过整道题，是比漏选项严重得多的错误。
7. **共享材料组**（试卷中多篇小题共用的原文${materialExamplesFor(specTypes)}）：先输出材料块（@@Q material=1 + @@P body，原文档有参考译文才加 @@P trans），随后紧跟依附它的小题，小题 @@Q 行加 group=prev；独立成题（作文等无共享原文）不加 group。${englishRules}分批转换时若本批只有材料没有题目、或只有题目没有材料，仍照常输出（group=prev 引用的是最终文档里其前的材料块）；**先材料、后小题**，材料块必须先于它的小题出现在本批输出里。
⚠️ **悬空禁止**：写 group=prev 的小题，其**本批之前**必须已经产出过材料块（同批内则材料块在本小题之前）——若本批之前从没产出材料块、本批也没有，说明这段文章语篇被漏了：**先补它的材料块（@@Q material=1 + @@P body）再写小题**，实在只是孤立小题（无共享原文）就不要写 group。
内容筛选（只出可考查的练习题，以下内容一律跳过、不得转成题目）：
- 讲义正文里夹带的**例题**（「例 1」「例 2」「【例】」「例题」等）及其示范解答——例题是讲解演示，不是练习，整段跳过。**例外：习题册的答案/解答不算例题**——「答案」「题解」类标题下、只有【解】【证】【分析】等求解过程的段落是练习内容而非讲解演示：把其中每道解答还原成**一道**完整题目输出（一解答只对应一题，求解过程写进解析），同样遵守第 4 条一题对一题；
- 章节开头的**引言/导读/学习目标**（「本章将介绍…」「学习目标」「导读」）——开场白没有可考知识点；
- 章末的**小结/重点回顾/知识框架/思维导图**（「本章小结」「重点回顾」「知识框架」）——收尾总结不出题；
判断依据是内容性质而非标题字面：讲解正文里附带完整解答的演示题即例题，习题册答案区的解答不是；只对知识做归纳梳理、无新考点的首尾段落即引言或小结。跳过这些内容后，按剩余正文的知识点正常出题。${fillRule}${stepsRule}${knowRuleBlock}${step ? stepRulesOf(step) : ""}

${step ? "本批原文片段" : "文档内容"}：
${source}${knowList}`;
}

/** 归纳 prompt。层级约定与就近挂靠语义对齐；禁空标题；方法层要求穷尽
 *  但有实质讲解门槛——纯名词罗列/发展史不升格为知识点（20260909 真机
 *  踩坑：自控原理绪论「发展史」一节的流派名词云被全量铺成 18 个 h3，
 *  占全树近半且污染路由词表）。20260910 自 KnowOutline 迁入。
 *  Issue #39 升级（20260912）：①**不收录**题干/例题/空壳噪音——导入语料
 *  （MinerU PDF 卷）的标题噪音原样上屏会污染面板与路由词表；②**例题
 *  反哺**允许参考例题把知识点切得更细；③节点可挂**源标题块指针**。 */
export function buildOutlinePrompt(content: string): string {
    return `你是知识点大纲整理器。把下面的章节内容归纳成一棵知识点大纲树，输出 markdown，只含标题与极简说明。这棵树服务于刷题：节点是做题时会用到的知识点。
层级约定（严格）：
# 知识大类（如：求极限 / 微分方程 / 级数）
## 具体方法或解法（如：洛必达法则 / 等价无穷小代换 / 夹逼准则；一阶线性 / 伯努利方程 / 傅里叶级数展开）
### 更细分（适用条件 / 典型陷阱 / 步骤要点；确无细分则省略整级）
不收录的内容（**排除项**，出现即不要进树）：
- 题号题干：「1.1 设…」「例 1.2 …」「习题 3.5」、「证」「解」「求」起头的整道题；
- 例题/示例/习题的标题（「例 1.2 求极限」「典型例题」「例题解析」等）；
- 空壳节：习题、解答、答案、综合题举例、基础习题精练、基础知识结构、本章小结、复习题 之类只作容器、不含知识点讲解的标题。
规则：
1. 最高从 # 开始；层级最深 ###；不要输出章节名本身当标题。
2. 每个标题必须实义，禁止「其他」「概述」「总结」这类空标题。
3. 每个 # 必须是本章实际讲到的知识主题，禁止起比本章更宽泛的学科名（本章讲「自动控制的一般概念」就不要起「自动控制理论基础」这类大一统标题）。
4. 方法层要穷尽内容中有实质讲解的方法与解法——正文有展开说明的才算，不要只挑两三个；一笔带过、纯名词罗列的内容（发展史、流派清单、课程框架）不单独立节点，至多合并成一个条目。
5. 面向做题价值：不出题的背景性、科普性内容不进树。
6. **例题反哺**：例题本身不进树，但要**读例题**——同一个方法在不同考查角度下反复出现时，据此把知识点切得更细、更贴考查点（例题里的适用条件、易错步骤、特殊情形都可升格为子节点）。
7. 每个叶标题下至多一行 30 字内的补充说明（可整篇省略）。
8. 只输出 markdown 标题树，格式之外不要输出任何文字。

章节内容：
${content}`;
}
